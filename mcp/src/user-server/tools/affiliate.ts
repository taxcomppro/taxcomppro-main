import { prisma } from "../../common/db.js";
import { UserSessionContext, formatSuccess, formatError, McpToolResponse } from "../../common/types.js";

export const affiliateToolDefinitions = [
  {
    name: "get_affiliate_overview",
    description: "Get affiliate performance metrics, referral link, commission rates, and pending balance.",
    inputSchema: {
      type: "object",
      properties: {},
    },
  },
  {
    name: "list_my_referrals",
    description: "List recent referrals and conversions generated by your affiliate link.",
    inputSchema: {
      type: "object",
      properties: {
        limit: { type: "number", description: "Maximum records to return (default: 20)" },
      },
    },
  },
  {
    name: "request_affiliate_payout",
    description: "Request a payout of your accumulated pending affiliate commission balance.",
    inputSchema: {
      type: "object",
      properties: {
        amount: { type: "number", description: "Amount in USD to withdraw" },
        method: { type: "string", enum: ["paypal", "stripe", "bank_transfer"], description: "Payout method" },
        details: { type: "string", description: "Payment destination (e.g. PayPal email or Bank account details)" },
      },
      required: ["amount", "method", "details"],
    },
  },
];

export async function handleAffiliateTool(
  toolName: string,
  args: any,
  user: UserSessionContext
): Promise<McpToolResponse> {
  try {
    const profile = await prisma.affiliateProfile.findUnique({
      where: { userId: user.userId },
    });

    switch (toolName) {
      case "get_affiliate_overview": {
        if (!profile) {
          return formatSuccess(
            { isAffiliate: false },
            "You are not registered as a TaxComPro affiliate partner yet."
          );
        }

        const settings = await prisma.affiliateSettings.findFirst();

        return formatSuccess({
          isAffiliate: true,
          referralCode: profile.code,
          referralUrl: `https://taxcomppro.com/?ref=${profile.code}`,
          totalEarned: profile.totalEarned,
          totalPaid: profile.totalPaid,
          pendingBalance: profile.pendingBalance,
          defaultCommissionRate: settings?.commissionVip ?? 20,
          customRate: profile.customCommissionRate,
          isActive: profile.isActive,
        });
      }

      case "list_my_referrals": {
        if (!profile) return formatError("You do not have an active affiliate profile.");

        const referrals = await prisma.affiliateReferral.findMany({
          where: { affiliateId: profile.id },
          include: {
            referredUser: {
              select: { name: true, tier: true, createdAt: true },
            },
          },
          orderBy: { createdAt: "desc" },
          take: Number(args.limit || 20),
        });

        return formatSuccess(referrals);
      }

      case "request_affiliate_payout": {
        if (!profile) return formatError("You do not have an active affiliate profile.");

        const { amount, method, details } = args;
        const requestedAmount = Number(amount);

        if (requestedAmount <= 0) {
          return formatError("Payout amount must be greater than 0.");
        }

        if (profile.pendingBalance < requestedAmount) {
          return formatError(
            `Insufficient pending balance. Available: $${profile.pendingBalance.toFixed(2)}, Requested: $${requestedAmount.toFixed(2)}`
          );
        }

        // Minimum payout threshold
        const settings = await prisma.affiliateSettings.findFirst();
        const minPayout = settings?.minPayoutAmount ?? 50;
        if (requestedAmount < minPayout) {
          return formatError(`Minimum payout amount is $${minPayout.toFixed(2)}.`);
        }

        const [payout] = await prisma.$transaction([
          prisma.affiliatePayout.create({
            data: {
              affiliateId: profile.id,
              amount: requestedAmount,
              method,
              details,
              status: "PENDING",
            },
          }),
          prisma.affiliateProfile.update({
            where: { id: profile.id },
            data: {
              pendingBalance: { decrement: requestedAmount },
            },
          }),
        ]);

        return formatSuccess(
          payout,
          `Payout request for $${requestedAmount.toFixed(2)} submitted for administrative review.`
        );
      }

      default:
        return formatError(`Unknown affiliate tool: ${toolName}`);
    }
  } catch (error: any) {
    return formatError(error.message || "Error executing affiliate tool", error);
  }
}
